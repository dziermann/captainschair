export type Language = keyof typeof uiTranslations;

export function useTranslations(lang: string) {
  const language = (lang in uiTranslations ? lang : 'en') as Language;
  return uiTranslations[language];
}

export function getTraitLabel(trait: string, lang: string): string {
  const t = useTranslations(lang);
  return (t.traitLabels as Record<string, string>)[trait] || trait;
}
